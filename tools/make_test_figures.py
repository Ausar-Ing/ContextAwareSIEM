#!/usr/bin/env python3
"""The four result figures of the locked run as pgfplots (LaTeX) files, generated from the frozen outputs.

Reads provenance/ait/test/test_recorded.json and test_norecon.json only; computes every plotted value the same way
as ait_report.py / ait_holm.py (seeded systems: mean over seeds; aggregates: mean over scenarios; coverage: summed
over scenarios); writes one tikzpicture per figure (no figure environment: captions belong to the document) and
prints the plotted values so they can be checked against the reports. Planned in provenance/ait/CLAIMS.md Section 8.

  fig_coverage.tex    non-scan stages first met in the top 20, per system, recorded and without reconnaissance
  fig_withinhost.tex  within-host AUC per eligible host: level rarity, B2, B_RBA; host rarity = 0.5 (chance)
  fig_recon.tex       alpha-nDCG@20 per system, recorded and without reconnaissance
  fig_firstrank.tex   first-item rank of every non-scan stage occurrence, both runs (B2_pooled: ablation)

Colours: one fixed colour per system in every figure (validated with the dataviz palette checks: B2 blue, B_RBA
orange, host rarity aqua, level rarity yellow; B2_pooled = B2's blue, hollow, different marker). Conditions in the
two per-system bar charts are neutral: solid (recorded) and hatched (without reconnaissance).

usage: python3 tools/make_test_figures.py tools provenance/ait/test References/results_test
"""
import json, os, sys
import numpy as np
sys.path.insert(0, sys.argv[1])
import eval_metrics as M

OUT, FIG = sys.argv[2], sys.argv[3]
os.makedirs(FIG, exist_ok=True)
R = {run: json.load(open(os.path.join(OUT, f"test_{run}.json"))) for run in ("recorded", "norecon")}
SCS = list(R["recorded"])
HEAD = "% generated by tools/make_test_figures.py from provenance/ait/test/{test_recorded,test_norecon}.json; do not edit by hand\n"
COLORS = r"""\providecolor{csB2}{HTML}{2A78D6}
\providecolor{csRBA}{HTML}{EB6834}
\providecolor{csHost}{HTML}{1BAF7A}
\providecolor{csRank}{HTML}{EDA100}
\providecolor{csInk}{HTML}{52514E}
\providecolor{csGrid}{HTML}{DDDCD7}
"""
LABEL = {"B0": r"B0", "B0_rank": r"B0$_\mathrm{rank}$", "B0_host": r"B0$_\mathrm{host}$", "B2": r"\textbf{B2}",
         "B2_pooled": r"B2$_\mathrm{pooled}$", "B3": r"B3", "B_RBA": r"B$_\mathrm{RBA}$"}
SYSTEMS = ("B0", "B0_rank", "B0_host", "B2", "B2_pooled", "B3", "B_RBA")
STAGES = (("online_cracking", "cracking"), ("attacker_change_user", "user change"), ("escalated_sudo_command", "sudo"))
AXIS = ("axis lines*=left, tick align=outside, tick style={csInk}, axis line style={csInk}, "
        "ymajorgrids, grid style={csGrid, line width=0.3pt}, label style={font=\\small}, tick label style={font=\\small}")


def rows(r, name):
    return r["seeded"].get(name) or [r["deterministic"][name]]


def mean_measure(run, name, key):
    """mean over scenarios of the per-scenario mean over seeds (as ait_report.py)"""
    return float(np.mean([np.mean([x[key] for x in rows(R[run][sc], name)]) for sc in SCS]))


def coverage(run, name):
    """non-scan stages first met in the top 20, summed over scenarios, mean over seeds"""
    return float(sum(np.mean([x["cov20"]["nonscan"][0] for x in rows(R[run][sc], name)]) for sc in SCS))


def first(run, sc, name, stage):
    xs = [x["first"][stage] for x in rows(R[run][sc], name) if stage in x["first"]]
    return float(np.mean(xs))


def write(name, body):
    open(os.path.join(FIG, name), "w").write(HEAD + COLORS + body)


def per_system_bars(fname, values, ylabel, ymax, ytick):
    xt = ",".join(LABEL[s] for s in SYSTEMS)
    coords = {run: " ".join(f"({i},{values[run][s]:.3f})" for i, s in enumerate(SYSTEMS)) for run in values}
    write(fname, rf"""\begin{{tikzpicture}}
\begin{{axis}}[width=\linewidth, height=5.4cm, ybar=1pt, bar width=9pt, {AXIS},
  ymin=0, ymax={ymax}, ytick={{{ytick}}}, ylabel={{{ylabel}}},
  xtick={{0,...,{len(SYSTEMS) - 1}}}, xticklabels={{{xt}}}, x tick label style={{font=\small}}, enlarge x limits=0.08,
  area legend, legend style={{draw=none, font=\small, at={{(0.02,0.98)}}, anchor=north west, fill=none}}, legend cell align=left]
\addplot[fill=csInk, draw=csInk] coordinates {{{coords["recorded"]}}};
\addplot[fill=white, draw=csInk, pattern=north east lines, pattern color=csInk] coordinates {{{coords["norecon"]}}};
\legend{{recorded (headline), without reconnaissance}}
\end{{axis}}
\end{{tikzpicture}}
""")


# figure 1: coverage
cov = {run: {s: coverage(run, s) for s in SYSTEMS} for run in R}
per_system_bars("fig_coverage.tex", cov, r"stages first met in the top 20 (of 10)", 10, "0,2,4,6,8,10")

# figure 3: alpha-nDCG@20, recorded vs without reconnaissance
nd = {run: {s: mean_measure(run, s, "andcg20") for s in SYSTEMS} for run in R}
per_system_bars("fig_recon.tex", nd, r"$\alpha$-nDCG@20", 0.8, "0,0.2,0.4,0.6,0.8")

# figure 2: within-host AUC per eligible host, recorded run
wh = []
for sc in SCS:
    hosts = rows(R["recorded"][sc], "B2")[0]["within_hosts"]
    for h, (_, na, nb) in hosts.items():
        v = {s: float(np.mean([x["within_hosts"][h][0] for x in rows(R["recorded"][sc], s)])) for s in ("B0_rank", "B2", "B_RBA")}
        wh.append((sc, h, na, nb, v))
xt = ",".join(f"{sc}" for sc, *_ in wh)
series = []
for s, col in (("B0_rank", "csRank"), ("B2", "csB2"), ("B_RBA", "csRBA")):
    c = " ".join(f"({i},{v[s]:.3f})" for i, (*_, v) in enumerate(wh))
    series.append(rf"\addplot[fill={col}, draw=white, line width=0.6pt] coordinates {{{c}}};")
write("fig_withinhost.tex", rf"""\begin{{tikzpicture}}
\begin{{axis}}[width=\linewidth, height=5.4cm, ybar=1pt, bar width=11pt, {AXIS},
  ymin=0, ymax=1.05, ytick={{0,0.25,0.5,0.75,1}}, ylabel={{within-host AUC}},
  xtick={{0,...,{len(wh) - 1}}}, xticklabels={{{xt}}}, enlarge x limits=0.15,
  legend style={{draw=none, font=\small, at={{(0.5,1.02)}}, anchor=south, fill=none, legend columns=-1, /tikz/every even column/.append style={{column sep=8pt}}}},
  area legend, legend cell align=left]
{chr(10).join(series)}
\draw[csHost, line width=1.2pt, dash pattern=on 4pt off 2pt] (axis cs:-0.5,0.5) -- (axis cs:{len(wh) - 0.5},0.5);
\addlegendimage{{line legend, csHost, line width=1.2pt, dash pattern=on 4pt off 2pt}}
\legend{{level rarity B0$_\mathrm{{rank}}$, B2, risk-based alerting B$_\mathrm{{RBA}}$, host rarity B0$_\mathrm{{host}}$ (0.5 on every host)}}
\end{{axis}}
\end{{tikzpicture}}
""")

# figure 4: first-item rank per stage occurrence, both runs
occ = [(sc, st, lab) for sc in SCS for st, lab in STAGES if st in rows(R["recorded"][sc], "B2")[0]["first"]]
ylabels = ",".join(f"{sc}: {lab}" for sc, _, lab in occ)
MARK = (("B0_host", "csHost", "mark=*, mark size=2.4pt", r"host rarity B0$_\mathrm{host}$"),
        ("B_RBA", "csRBA", "mark=square*, mark size=2.2pt", r"risk-based alerting B$_\mathrm{RBA}$"),
        ("B2", "csB2", "mark=triangle*, mark size=2.8pt", r"B2"),
        ("B2_pooled", "csB2", "mark=diamond, mark size=2.8pt, mark options={line width=1pt, fill=white}", r"B2$_\mathrm{pooled}$ (ablation)"))
panels = []
for k, (run, title) in enumerate((("recorded", "recorded (headline)"), ("norecon", "without reconnaissance"))):
    plots = []
    for s, col, mk, lab in MARK:
        c = " ".join(f"({first(run, sc, s, st):.1f},{len(occ) - i})" for i, (sc, st, _) in enumerate(occ))
        plots.append(rf"\addplot[only marks, color={col}, {mk}] coordinates {{{c}}};" + (rf" \addlegendentry{{{lab}}}" if k == 0 else ""))
    yt = (rf"ytick={{1,...,{len(occ)}}}, yticklabels={{{','.join(reversed(ylabels.split(',')))}}}, legend to name=firstranklegend," if k == 0 else
          rf"ytick={{1,...,{len(occ)}}}, yticklabels={{}},")
    panels.append(rf"""\nextgroupplot[title={{{title}}}, {yt}]
{chr(10).join(plots)}""")
write("fig_firstrank.tex", rf"""\begin{{tikzpicture}}
\begin{{groupplot}}[group style={{group size=2 by 1, horizontal sep=0.35cm}}, scale only axis, width=0.36\linewidth, height=6.4cm,
  xmode=log, xmin=0.8, xmax=110, xtick={{1,2,5,10,20,50,100}}, xticklabels={{1,2,5,10,20,50,100}},
  xlabel={{rank of the first item (log; lower = earlier)}}, ymin=0.4, ymax={len(occ) + 0.6},
  axis lines*=left, tick align=outside, tick style={{csInk}}, axis line style={{csInk}},
  xmajorgrids, ymajorgrids, grid style={{csGrid, line width=0.3pt}}, label style={{font=\small}},
  tick label style={{font=\small}}, title style={{font=\small}},
  legend style={{draw=none, font=\small, fill=none, legend columns=2, /tikz/every even column/.append style={{column sep=8pt}}}}]
{chr(10).join(panels)}
\end{{groupplot}}
\node[anchor=north] at ($(group c1r1.south east)!0.5!(group c2r1.south west) + (0,-1.1cm)$) {{\pgfplotslegendfromname{{firstranklegend}}}};
\end{{tikzpicture}}
""")

# check output: every plotted value, to compare with the reports
print("coverage@20 non-scan:", {r: {s: round(v, 1) for s, v in cov[r].items()} for r in cov})
print("alpha-nDCG@20:", {r: {s: round(v, 3) for s, v in nd[r].items()} for r in nd})
print("within-host AUC (recorded):", [(sc, h, na, nb, {s: round(x, 3) for s, x in v.items()}) for sc, h, na, nb, v in wh])
for run in R:
    print(f"first-item ranks ({run}):", [(sc, lab, {s: round(first(run, sc, s, st), 1) for s, *_ in MARK}) for sc, st, lab in occ])
